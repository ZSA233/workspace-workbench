export function localizedReviewError(error: { code?: unknown } | null | undefined, source: WorkbenchCopy, fallback?: string): string {
  const code = typeof error?.code === "string" ? error.code.split(":", 1)[0] : "";
  return reviewErrorKeys[code] ? source[reviewErrorKeys[code]] : fallback || source.reviewErrorGeneric;
}
