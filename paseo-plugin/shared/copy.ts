export const copy: WorkbenchCopy = zhCopy;

function localeCandidate(value: unknown): string | null {
  if (typeof value === "string") return value;
  if (!value || typeof value !== "object") return null;
  const record = value as Record<string, unknown>;
  for (const key of ["locale", "language", "languageTag"]) {
    if (typeof record[key] === "string") return record[key] as string;
  }
  return null;
}

export function normalizeWorkbenchLocale(value: unknown): WorkbenchLocale | null {
  const candidate = localeCandidate(value)?.toLowerCase();
  if (!candidate) return null;
  return candidate === "zh" || candidate.startsWith("zh-") ? "zh-CN" : "en-US";
}

export function resolveWorkbenchLocale(input?: unknown): WorkbenchLocale {
  const explicit = normalizeWorkbenchLocale(input);
  if (explicit) return explicit;
  const runtime = globalThis as unknown as { navigator?: { language?: string }; Intl?: typeof Intl };
  const browser = normalizeWorkbenchLocale(runtime.navigator?.language);
  if (browser) return browser;
  try {
    const system = normalizeWorkbenchLocale(Intl.DateTimeFormat().resolvedOptions().locale);
    if (system) return system;
  } catch {
    // Hosts without Intl use the compatibility default below.
  }
  return "zh-CN";
}

export function getWorkbenchCopy(locale: WorkbenchLocale = "zh-CN"): WorkbenchCopy {
  return locale === "en-US" ? enCopy : zhCopy;
}

export function formatCopyFrom(source: WorkbenchCopy, key: keyof WorkbenchCopy, values: unknown[]): string {
  return source[key].replace(/\{(\d+)\}/g, (_, index) => String(values[Number(index)] ?? ""));
}

export function formatCopy(key: keyof WorkbenchCopy, values: unknown[]): string {
  return formatCopyFrom(copy, key, values);
}

